"""
Additional UI translations for all 32 non-English KDE languages.

`src_gui/i18n.py` is generated by `tools/generate_i18n.py`; strings added later live here
and are merged into `TRANSLATIONS` at import time (`merge_into`). An entry only replaces a
translation that is missing or is just a copy of the English text.

Each entry: (english_key, [translations in LANG_ORDER]).
"""

LANG_ORDER = [
    "pt", "es", "ja", "de", "fr", "it", "ru", "zh_CN", "zh_TW", "ko", "pl", "nl", "uk", "tr", "sv", "cs",
    "ca", "ar", "hi", "hu", "da", "fi", "nb", "el", "id", "ro", "sk", "sl", "bg", "eu", "gl", "et",
]

ENTRIES = []


def add(*items):
    for key, values in items:
        if len(values) != len(LANG_ORDER):
            raise ValueError(f"i18n_extra: '{key}' has {len(values)} translations, expected {len(LANG_ORDER)}")
        ENTRIES.append((key, values))


def merge_into(translations):
    """Adds the entries to the TRANSLATIONS dict (missing or English-copy values only)."""
    en = translations.setdefault("en", {})
    for key, values in ENTRIES:
        en.setdefault(key, key)
        for code, text in zip(LANG_ORDER, values):
            lang = translations.setdefault(code, {})
            current = lang.get(key)
            if current is None or current == key:
                lang[key] = text
    return translations


